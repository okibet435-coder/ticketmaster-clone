function renderTickets() {
  const text = currentText();
  const upcomingEvents = state.events.filter((event) => new Date(event.date) >= new Date());
  const pastEvents = state.events.filter((event) => new Date(event.date) < new Date());
  const list = state.ticketFilter === 'upcoming' ? upcomingEvents : pastEvents;

  els.eventManagerLabel.textContent = text.eventManager;
  els.openAddEventBtn.textContent = text.addEvent;
  document.querySelector('.subtab[data-state="upcoming"]').textContent = text.upcoming;
  document.querySelector('.subtab[data-state="past"]').textContent = text.past;

  if (!list.length) {
    els.ticketList.innerHTML = `<div class="empty-state">No ${state.ticketFilter} tickets yet.</div>`;
    return;
  }

  els.ticketList.innerHTML = list
    .map((event) => {
      const transfer = state.transfers.find((item) => item.ticketId === event.id && item.status === 'pending');
      return `
        <article class="ticket-card">
          <div class="ticket-content">
            <div class="ticket-head">
              <h4 class="ticket-title">${event.showTitle}</h4>
              <span class="ticket-status">${event.ticketType}</span>
            </div>

            <div class="ticket-layout" style="margin-top: 12px;">
              <div class="ticket-thumb" style="background-image: url('${event.imageLink}')"></div>
              <div class="ticket-info">
                <strong>${event.location}</strong>
                <span>${formatDate(event.date)} • ${event.time}</span>
                <span>${event.venue}</span>
                <span>Seat ${event.seatStart} • Row ${event.row} • Sec ${event.section}</span>
              </div>
            </div>

            ${
              transfer
                ? `
                  <div class="transfer-box">
                    <span class="pending-tag">${text.pendingTransfer}</span>
                    <strong>${text.transferTo}: ${transfer.firstName}</strong>
                    <div class="transfer-email">${transfer.emailPhone}</div>
                    <div class="transfer-actions">
                      <button class="mini-btn" data-edit-transfer="${transfer.id}">${text.edit}</button>
                      <button class="mini-btn delete" data-delete-transfer="${transfer.id}">${text.delete}</button>
                    </div>
                  </div>
                `
                : ''
            }

            <div class="action-row">
              <button class="btn btn-primary" data-edit-event="${event.id}">Edit event</button>
              <button class="btn btn-ghost" data-delete-event="${event.id}">Delete</button>
            </div>
          </div>
        </article>
      `;
    })
    .join('');

  els.ticketList.querySelectorAll('[data-edit-event]').forEach((button) => {
    button.addEventListener('click', () => openEventModal(Number(button.dataset.editEvent)));
  });

  els.ticketList.querySelectorAll('[data-delete-event]').forEach((button) => {
    button.addEventListener('click', () => {
      const eventId = Number(button.dataset.deleteEvent);
      state.events = state.events.filter((event) => event.id !== eventId);
      state.transfers = state.transfers.filter((transfer) => transfer.ticketId !== eventId);
      renderAll();
    });
  });

  els.ticketList.querySelectorAll('[data-edit-transfer]').forEach((button) => {
    button.addEventListener('click', () => {
      const transferId = Number(button.dataset.editTransfer);
      const transfer = state.transfers.find((item) => item.id === transferId);
      if (!transfer) return;
      document.getElementById('transferFirstName').value = transfer.firstName;
      document.getElementById('transferLastName').value = transfer.lastName;
      document.getElementById('transferEmailPhone').value = transfer.emailPhone;
      document.getElementById('transferNote').value = transfer.note;
      state.currentTransferId = transferId;
      state.currentTicketId = transfer.ticketId;
      els.transferModal.classList.add('visible');
    });
  });

  els.ticketList.querySelectorAll('[data-delete-transfer]').forEach((button) => {
    button.addEventListener('click', () => {
      const transferId = Number(button.dataset.deleteTransfer);
      state.transfers = state.transfers.filter((transfer) => transfer.id !== transferId);
      renderAll();
    });
  });
}

