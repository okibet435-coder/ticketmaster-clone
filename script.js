function currentText() {
  return translations[state.lang] || translations.en;
}

function formatDate(dateString) {
  const date = new Date(dateString + 'T12:00:00');
  return date.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
    year: 'numeric',
  });
}

function setLanguage(lang) {
  state.lang = lang;
  els.languageSelect.value = lang;
  renderAll();
}

function switchTab(tabName) {
  state.activeTab = tabName;

  document.querySelectorAll('.tab-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.tab === tabName);
  });

  document.querySelectorAll('.panel').forEach((panel) => {
    panel.classList.toggle('active', panel.id === `${tabName}-panel`);
  });

  document.querySelectorAll('.nav-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.nav === tabName);
  });
}

function getFilteredEvents() {
  const query = state.search.trim().toLowerCase();
  return state.events.filter((event) => {
    if (!query) return true;
    const combined = [
      event.showTitle,
      event.location,
      event.venue,
      event.country,
      event.ticketType,
    ]
      .join(' ')
      .toLowerCase();
    return combined.includes(query);
  });
}

function renderDiscover() {
  const text = currentText();
  els.discoverTitle.textContent = text.discoverTitle;
  els.globalSearch.placeholder = text.searchPlaceholder;
  document.getElementById('locationsLabel').textContent = text.locations;
  document.getElementById('datesLabel').textContent = text.dates;

  const data = getFilteredEvents();

  if (!data.length) {
    els.discoverList.innerHTML = '<div class="empty-state">No events match your search.</div>';
    return;
  }

  els.discoverList.innerHTML = data
    .map(
      (event) => `
        <article class="event-card">
          <div class="event-visual" style="background-image: url('${event.imageLink}')">
            <span class="country-badge">${event.country}</span>
          </div>
          <div class="event-content">
            <div class="event-head">
              <h4 class="event-title">${event.showTitle}</h4>
              <button class="favorite-btn ${event.favorite ? 'active' : ''}" data-favorite="${event.id}" aria-label="favorite">
                ${event.favorite ? '♥' : '♡'}
              </button>
            </div>

            <div class="meta-list">
              <div class="meta-row">📅 <span>${formatDate(event.date)} • ${event.dayOfWeek}</span></div>
              <div class="meta-row">🕒 <span>${event.time}</span></div>
              <div class="meta-row">📍 <span>${event.location} • ${event.venue}</span></div>
            </div>

            <div class="action-row">
              <button class="btn btn-primary" data-buy="${event.id}">Get tickets</button>
              <button class="btn btn-light" data-transfer="${event.id}">Transfer</button>
            </div>
          </div>
        </article>
      `
    )
    .join('');

  els.discoverList.querySelectorAll('[data-favorite]').forEach((button) => {
    button.addEventListener('click', () => {
      const eventId = Number(button.dataset.favorite);
      const event = state.events.find((item) => item.id === eventId);
      if (event) {
        event.favorite = !event.favorite;
        renderAll();
      }
    });
  });

  els.discoverList.querySelectorAll('[data-buy]').forEach((button) => {
    button.addEventListener('click', () => {
      const eventId = Number(button.dataset.buy);
      openEventModal(eventId);
    });
  });

  els.discoverList.querySelectorAll('[data-transfer]').forEach((button) => {
    button.addEventListener('click', () => {
      openTransferModal(Number(button.dataset.transfer));
    });
  });
}

