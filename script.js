  document.querySelector('.nav-btn[data-nav="favorite"] small').textContent = text.favorite;
  document.querySelector('.nav-btn[data-nav="tickets"] small').textContent = text.myTicket;
  document.querySelector('.nav-btn[data-nav="account"] small').textContent = text.myAccount;

